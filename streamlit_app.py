def safe_metric(df: pd.DataFrame, col: str, fn: str):
    if col not in df.columns:
        return "N/A"
    series = pd.to_numeric(df[col], errors="coerce").dropna()
    if series.empty:
        return "N/A"
    if fn == "min":
        return f"{series.min():.4f}"
    if fn == "median":
        return f"{series.median():.4f}"
    if fn == "max":
        return f"{series.max():.4f}"
    return "N/A"


